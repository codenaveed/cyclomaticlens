/**
 * Calculator utility.
 */
public class Calc {
    /**
     * Adds two numbers.
     * @param a first
     * @param b second
     * @return sum
     */
    public int add(int a, int b) {
        return a + b;
    }

    /**
     * Multiplies two numbers.
     * @param a first
     * @param b second
     * @return product
     */
    public int multiply(int a, int b) {
        return a * b;
    }
}
